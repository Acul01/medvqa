"""Conversation builder for FGR evaluation Settings A–E.

All five settings share the same prompt structure — the MC question,
the reasoning trace *r*, and an optional image.  Only the *image*
argument differs across settings:

    Setting A  →  image=None          (text-only; tests linguistic self-consistency)
    Setting B  →  image=full_image    (reference condition)
    Setting C  →  image=relevant_crop (visual sufficiency)
    Setting D  →  image=irrelevant_crop, size-matched (shortcut / language-prior)
    Setting E  →  image=mean_filled   (visual necessity)
"""
from __future__ import annotations

from typing import Optional

from PIL import Image

from utils.mc_vqa import LETTER_POOL


def build_fgr_conversation(
    question: str,
    options: list[str],
    reasoning: str,
    *,
    image: Optional[Image.Image] = None,
) -> list[dict]:
    """Build a Qwen2.5-VL chat conversation for one FGR evaluation setting.

    The prompt places the answer instruction *after* the reasoning trace so
    the model reads the chain-of-thought before committing to a letter.

    Parameters
    ----------
    question:
        Original MC question text.
    options:
        List of answer-option strings (length ≥ 2).
    reasoning:
        Chain-of-thought reasoning trace *r* generated by MedVLM-R1.
    image:
        PIL Image for the setting, or ``None`` for Setting A (text-only).
    """
    option_lines = "\n".join(
        f"{LETTER_POOL[i]}) {opt.strip()}" for i, opt in enumerate(options)
    )
    allowed = ", ".join(LETTER_POOL[: len(options)])
    image_clause = " and the image" if image is not None else ""

    prompt = (
        f"{question.strip()}\n\n"
        f"Options:\n{option_lines}\n\n"
        f"Medical reasoning:\n{reasoning.strip()}\n\n"
        f"Based on the above reasoning{image_clause}, "
        f"answer with exactly one letter from {allowed}. "
        "Do not output any other text."
    )

    content: list[dict] = []
    if image is not None:
        content.append({"type": "image", "image": image})
    content.append({"type": "text", "text": prompt})

    return [{"role": "user", "content": content}]
